module encoder_10to4 (
    input wire [9:0] in,
    output wire [3:0] out
);
assign out = (in == 10'b0000000001) ? 4'b0000 :
             (in == 10'b0000000010) ? 4'b0001 :
             (in == 10'b0000000100) ? 4'b0010 :
             (in == 10'b0000001000) ? 4'b0011 :
             (in == 10'b0000010000) ? 4'b0100 :
             (in == 10'b0000100000) ? 4'b0101 :
             (in == 10'b0001000000) ? 4'b0110 :
             (in == 10'b0010000000) ? 4'b0111 :
             (in == 10'b0100000000) ? 4'b1000 :
             (in == 10'b1000000000) ? 4'b1001 : 4'b0000;
    
endmodule
