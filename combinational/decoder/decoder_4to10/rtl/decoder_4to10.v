module decoder_4to10 (
    input wire [3:0] in,
    output wire [9:0] out
);
    assign out =(in == 4'b0000) ? 10'b0000000001 :
        (in == 4'b0001) ? 10'b0000000010 :
        (in == 4'b0010) ? 10'b0000000100 :
        (in == 4'b0011) ? 10'b0000001000 :
        (in == 4'b0100) ? 10'b0000010000 :
        (in == 4'b0101) ? 10'b0000100000 :
        (in == 4'b0110) ? 10'b0001000000 :
        (in == 4'b0111) ? 10'b0010000000 :
        (in == 4'b1000) ? 10'b0100000000 :
        (in == 4'b1001) ? 10'b1000000000 : 10'b0000000000;          

endmodule